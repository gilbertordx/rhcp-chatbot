"""Capture expected outputs from the ORIGINAL Python code into rust/tests/golden.json,
so `cargo test` can check the Rust port without needing Python installed.
usage: python make_golden.py <repo-root>"""
import asyncio, contextlib, io, json, logging, os, sys, warnings
warnings.filterwarnings("ignore"); logging.disable(logging.CRITICAL)
repo = sys.argv[1]; os.chdir(repo); sys.path.insert(0, repo)
from nltk.stem import PorterStemmer
from nltk.tokenize import word_tokenize
from app.chatbot.initializer import initialize_chatbot
from app.chatbot.memory import ConversationMemory
import app.core.inference as inf
from app.knowledge import resolver as res

token_cases = ["who is flea?", "Tell me about Under the Bridge. also the album's tracks!", "I don't know... what's up?! (really)", "going. use your brain",
               "Mr. Smith went to Washington. He was a U.S. senator.", "it cost $3.88 (roughly 3,36 euros) in New York.", "He said \"hello there\" and left.",
               "cannot gimme gonna wanna", "“curly” quotes — and dashes", "running ponies caresses happiness relational", "", "   "]
stemmer = PorterStemmer()
tokens = [{"text": t, "words": word_tokenize(t), "stems": [stemmer.stem(w) for w in word_tokenize(t.lower())]} for t in token_cases]

with contextlib.redirect_stdout(io.StringIO()):
    processor = asyncio.run(initialize_chatbot())
    inf.initialize_inference(processor, ConversationMemory())
messages = ["bye", "hello", "who is flea", "tell me about californication", "who are the members of the band", "what is the best pizza",
            "tell me about anthony kiedis", "under the bridge", "when was blood sugar sex magik released", "thanks", "who plays drums", "scar tissue",
            "John Frusciante and Chad Smith", "stadium arcadium", "what year was by the way released"]
classify = []
pipeline = []
for m in messages:
    ranked = processor.get_classifications(m.lower())
    classify.append({"text": m, "top": [[r["label"], r["value"]] for r in ranked[:3]]})
    r = inf.run_inference(m).model_dump()
    pipeline.append({"text": m, "intent": r["intent"], "confidence": r["confidence"], "raw_intent": r["raw_intent"],
                     "raw_confidence": r["raw_confidence"], "entity_types": [e["type"] for e in r["entities"]],
                     "entity_names": [e["value"].get("name") for e in r["entities"]], "final_message": r["final_message"]})
resolver = res.get_knowledge_resolver()
spans = ["flea", "fruciante", "FRUSCIANTE", "bssm", "californication", "under the bridge", "utb", "kiedus", "caliphornication", "Björk", "", "zzz"]
n = lambda v: v["canonical"] if v else None
resolve = [{"span": s, "member": n(resolver.resolve_member(s)), "album": n(resolver.resolve_album(s)), "song": n(resolver.resolve_song(s)), "norm": resolver._normalize_span(s)} for s in spans]
json.dump({"note": "generated by tools/make_golden.py from the original Python code", "tokens": tokens, "classify": classify, "pipeline": pipeline, "resolve": resolve},
          open(f"{repo}/rust/tests/golden.json", "w"), indent=1, ensure_ascii=False)
print("wrote rust/tests/golden.json:", len(tokens), "token cases,", len(classify), "classifications,", len(resolve), "resolver spans")
